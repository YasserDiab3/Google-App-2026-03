    const literalEnToAr = Object.fromEntries(Object.entries(literalArToEn).map(([ar, en]) => [en, ar]));

    function escapeRegExp(text) {
        return String(text).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    }

    function replaceLiteralSafely(input, from, to) {
        if (!input || !from || from === to) return input;
        if (input === from) return to;
        if (!input.includes(from)) return input;

        // Replace only when the literal is not embedded inside another Arabic/Latin word.
        const escaped = escapeRegExp(from);
        const pattern = new RegExp(`(^|[^A-Za-z0-9_\\u0600-\\u06FF])(${escaped})(?=$|[^A-Za-z0-9_\\u0600-\\u06FF])`, 'g');
        return input.replace(pattern, (match, prefix) => `${prefix}${to}`);
    }

    function getCurrentLang() {
        return (global.localStorage && localStorage.getItem('language')) || global?.AppState?.currentLanguage || 'ar';
    }

    function t(key, lang, fallback = '') {
        const selectedLang = lang || getCurrentLang();
        return (translations[selectedLang]?.[key] ?? translations.ar?.[key] ?? fallback) || key;
    }

    function applyI18n(root = document, lang) {
        const selectedLang = lang || getCurrentLang();
        const target = root || document;

        target.querySelectorAll?.('[data-i18n]').forEach((el) => {
            const key = el.getAttribute('data-i18n');
            if (!key) return;
            el.textContent = t(key, selectedLang, el.textContent || '');
        });

        target.querySelectorAll?.('[data-i18n-title]').forEach((el) => {
            const key = el.getAttribute('data-i18n-title');
            if (!key) return;
            el.setAttribute('title', t(key, selectedLang, el.getAttribute('title') || ''));
        });

        target.querySelectorAll?.('[data-i18n-placeholder]').forEach((el) => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (!key) return;
            el.setAttribute('placeholder', t(key, selectedLang, el.getAttribute('placeholder') || ''));
        });

        target.querySelectorAll?.('[data-i18n-aria-label]').forEach((el) => {
            const key = el.getAttribute('data-i18n-aria-label');
            if (!key) return;
            el.setAttribute('aria-label', t(key, selectedLang, el.getAttribute('aria-label') || ''));
        });
    }

    function applyLiteralTranslations(root = document, lang) {
        const selectedLang = lang || getCurrentLang();
        const map = selectedLang === 'en' ? literalArToEn : literalEnToAr;
        const target = root || document;
        const entries = Object.entries(map).sort((a, b) => b[0].length - a[0].length);

        const walker = document.createTreeWalker(target, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) {
            const original = node.nodeValue;
            if (!original || !original.trim()) continue;
            let updated = original;
            entries.forEach(([from, to]) => {
                if (!from || from === to) return;
                updated = replaceLiteralSafely(updated, from, to);
            });
            if (updated !== original) {
                node.nodeValue = updated;
            }
        }

        target.querySelectorAll?.('[title], [placeholder], [aria-label]').forEach((el) => {
            ['title', 'placeholder', 'aria-label'].forEach((attr) => {
                const value = el.getAttribute(attr);
                if (!value) return;
                let updated = value;
                entries.forEach(([from, to]) => {
                    if (!from || from === to) return;
                    updated = replaceLiteralSafely(updated, from, to);
                });
                if (updated !== value) {
                    el.setAttribute(attr, updated);
                }
            });
        });
    }

    let observerAttached = false;
    function observeDomForI18n() {
        if (observerAttached || !global.MutationObserver || !document?.body) return;
        observerAttached = true;
        const observer = new MutationObserver((mutations) => {
            const lang = getCurrentLang();
            mutations.forEach((mutation) => {
                mutation.addedNodes.forEach((node) => {
                    if (!(node instanceof HTMLElement)) return;
                    applyI18n(node, lang);
                    applyLiteralTranslations(node, lang);
                });
            });
        });
        observer.observe(document.body, { childList: true, subtree: true });
    }

    const coreI18n = {
        translations,
        literalArToEn,
        t,
        applyI18n,
        applyLiteralTranslations,
        observeDomForI18n,
        getCurrentLang
    };

    // Expose a dedicated namespace to avoid collisions with legacy window.I18n in app-utils.
    global.AppI18n = coreI18n;

    // Merge capabilities into existing window.I18n if it already exists.
    if (global.I18n && typeof global.I18n === 'object') {
        global.I18n = { ...global.I18n, ...coreI18n };
    } else {
        global.I18n = coreI18n;
    }
